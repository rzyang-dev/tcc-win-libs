/* txt2c - 把文本文件转成 C 字符串数组（与 luac2c 配对使用） */
#include <stdio.h>
#include <stdlib.h>

static void sanitize(char *s) {
    for (; *s; s++)
        if (!((*s >= 'a' && *s <= 'z') || (*s >= 'A' && *s <= 'Z') ||
              (*s >= '0' && *s <= '9') || *s == '_')) *s = '_';
}

int main(int argc, char **argv) {
    if (argc != 4) {
        fprintf(stderr, "usage: txt2c <input> <output.c> <symbol>\n");
        return 2;
    }
    char sym[128];
    snprintf(sym, sizeof sym, "%s", argv[3]);
    sanitize(sym);

    FILE *f = fopen(argv[1], "rb");
    if (!f) { fprintf(stderr, "cannot open %s\n", argv[1]); return 1; }
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *buf = (unsigned char *)malloc((size_t)n);
    if (fread(buf, 1, (size_t)n, f) != (size_t)n) { fclose(f); free(buf); return 1; }
    fclose(f);

    FILE *o = fopen(argv[2], "wb");
    if (!o) { free(buf); return 1; }
    fprintf(o, "/* generated by txt2c from %s -- do not edit */\n\n", argv[1]);
    fprintf(o, "const char %s[] = {\n", sym);
    for (long i = 0; i < n; i++) {
        if (i % 16 == 0) fprintf(o, "  ");
        fprintf(o, "0x%02x,", buf[i]);
        if (i % 16 == 15) fprintf(o, "\n"); else fprintf(o, " ");
    }
    if (n % 16) fprintf(o, "\n");
    /* 不加 NUL：消费方一律用显式长度，多一个字节会让字节码读错 */
    fprintf(o, "};\n\n");
    fprintf(o, "const unsigned int %s_len = %u;\n", sym, (unsigned)n);
    fclose(o);
    free(buf);
    printf("txt2c: %s (%ld bytes) -> %s as '%s'\n", argv[1], n, argv[2], sym);
    return 0;
}
