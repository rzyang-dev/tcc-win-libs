/* math_compat.c —— float 数学函数的正确实现（宏做不到的那些）
 *
 * ============================================================
 * 为什么需要这个文件
 * ============================================================
 *
 * `tccmath.h` 用宏把不可用的 float 函数转发到双精度版，这对**单参数**
 * 函数没问题。但有函数**接受指针出参**，宏就做不到 —— 最典型的是 `modff`：
 *
 *     float modff(float x, float *iptr);      // iptr 是 **4 字节 float***
 *
 * 双精度版 `modf` 的第二参数是 `double *`，会写 **8 字节**。
 *
 * 曾经在 tccmath.h 里写成：
 *
 *     #define modff(x,ip) ((float)modf((double)(x), (double *)(ip)))
 *
 * **这是有害的**，两个后果（实测确认）：
 *
 *   1. 整数部分的值不对 —— `modff(3.75f,&f)` 得到 `int=0.00` 而不是 3.00
 *   2. **越界写 4 字节栈内存** —— 静默破坏相邻变量，
 *      而且 `modf` 的返回值（小数部分）恰好是对的，所以**极难发现**
 *
 * 所以改成"tccmath.h 只声明，本文件提供实现"，由 `-With math` 启用。
 *
 * **刻意不在 -With math 时调用 `modff` 会链接失败** —— 这是有意的：
 * **宁可链接失败，也不要静默越界写**。
 *
 * 用法：scripts\tcc.cmd app.c -With math
 *
 * ============================================================
 * 本文件还提供什么
 * ============================================================
 *
 *   modff     —— 见上，唯一"宏做不到"的那个
 *   frexpf    —— 同样有 int* 出参（但 int 是 4 字节，宏其实能用；
 *                放这里是为了 modff 有个伴，且避免宏的重复求值问题）
 *
 * 其余 float 函数（sqrtf / sinhf / copysignf 等）都由 tccmath.h 的宏处理，
 * 不需要本文件。
 *
 * 「未验证边界」见文件末尾。
 */

#include "tccmath.h"        /* 拿到声明，且确保 math.h 已包含 */
#include <math.h>

/* ============================================================
 * modff
 * ============================================================
 *
 * 正确实现必须用 double 中转，不能把 float* 直接当 double* 用。 */
float modff(float x, float *iptr)
{
    double di = 0.0;
    double df;

    df = modf((double)x, &di);

    if (iptr) *iptr = (float)di;
    return (float)df;
}

/* ============================================================
 * 为什么**没有** frexpf
 * ============================================================
 *
 * 原计划把 `frexpf` 也放这里，但实测它在 32 位与 64 位下**都已经有定义**
 * （`math.h` 里那份 `__CRT_INLINE` 是**带定义**的），在这里再写一遍会得到：
 *
 *     redefinition of 'frexpf'
 *
 * 所以本文件**只提供 `modff`** —— 唯一一个"宏做不到、又真的缺"的。
 *
 * 教训：**补之前先确认真的缺**。判据与 P73/P74 一致：
 * 不加 `-I`、带 `-L`，编译与链接同时过才算可用。 */


/* ============================================================
 * 未验证边界
 * ============================================================
 *
 *   - `modff` 只测过常规值（3.75f / 9.5f）。**未测**：
 *     极大/极小值、±0.0、±Inf、NaN、次正规数（denormal）。
 *   - `modff` 的整数部分用 `(float)di` 收窄。当 |x| 超过 float 能精确
 *     表示的整数范围（约 1.6e7）时，收窄会有舍入 —— 这与标准库行为一致，
 *     但**未逐值验证**。
 *   - 本文件只提供 `modff` 一个函数。其余 float 数学函数走 `tccmath.h` 的宏，
 *     **不需要**本文件。
 */
