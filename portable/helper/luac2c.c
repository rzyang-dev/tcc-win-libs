/* luac2c.h - 把 .luac 字节码转成 C 数组的构建工具
 *
 * 用途：在构建期把 Lua 脚本预编译成字节码并嵌入 C 源码，
 * 使便携工具保持单文件、零外部依赖，同时把启动解析开销降低约 8 倍。
 *
 * 用法：
 *   luac55.exe -s -o script.luac script.lua
 *   luac2c.exe script.luac script_luac.c tcwin_script
 *   然后在程序里：
 *     extern const unsigned char tcwin_script[];
 *     extern const unsigned int  tcwin_script_len;
 *     luaL_loadbuffer(L, (const char*)tcwin_script, tcwin_script_len, "=tcwin_script");
 *
 * 之所以用 .luac 而不是在运行时 luaL_loadstring 源码：
 *   - 源码解析约 6.7 us/行；字节码加载约 0.8 us/行（实测 8x）
 *   - 18000 行脚本：源码 56ms -> 字节码 7ms
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static void sanitize(char *s) {
    for (; *s; s++) {
        if (!((*s >= 'a' && *s <= 'z') || (*s >= 'A' && *s <= 'Z') ||
              (*s >= '0' && *s <= '9') || *s == '_')) *s = '_';
    }
}

int main(int argc, char **argv) {
    if (argc != 4) {
        fprintf(stderr,
            "luac2c - embed Lua bytecode as a C array\n"
            "usage: luac2c <input.luac> <output.c> <symbol>\n");
        return 2;
    }
    const char *inpath = argv[1], *outpath = argv[2];
    char sym[128];
    snprintf(sym, sizeof sym, "%s", argv[3]);
    sanitize(sym);

    FILE *f = fopen(inpath, "rb");
    if (!f) { fprintf(stderr, "cannot open %s\n", inpath); return 1; }
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (n <= 0) { fprintf(stderr, "%s is empty\n", inpath); fclose(f); return 1; }
    unsigned char *buf = (unsigned char *)malloc((size_t)n);
    if (fread(buf, 1, (size_t)n, f) != (size_t)n) {
        fprintf(stderr, "short read on %s\n", inpath); fclose(f); free(buf); return 1;
    }
    fclose(f);

    FILE *o = fopen(outpath, "wb");
    if (!o) { fprintf(stderr, "cannot write %s\n", outpath); free(buf); return 1; }

    fprintf(o, "/* generated by luac2c from %s -- do not edit */\n", inpath);
    fprintf(o, "#include <stddef.h>\n\n");
    fprintf(o, "const unsigned char %s[] = {\n", sym);
    for (long i = 0; i < n; i++) {
        if (i % 16 == 0) fprintf(o, "  ");
        fprintf(o, "0x%02x,", buf[i]);
        if (i % 16 == 15) fprintf(o, "\n");
        else fprintf(o, " ");
    }
    if (n % 16) fprintf(o, "\n");
    fprintf(o, "};\n\n");
    fprintf(o, "const unsigned int %s_len = %u;\n", sym, (unsigned)n);

    fclose(o);
    free(buf);
    printf("luac2c: %s (%ld bytes) -> %s as '%s'\n", inpath, n, outpath, sym);
    return 0;
}
